"""
Generate braas_hpc_xmlmaterial_sockets.py from the Cycles shader node definitions.

The XML reader of CyclesPhi (src/graph/node_xml_bin.cpp, src/app/cycles_xml_bin.cpp) resolves
<socket> and <connect> entries against the Cycles NodeType sockets, so the exporter needs to know
the Cycles socket names of every shader node. They are parsed from the NODE_DEFINE blocks of
src/scene/shader_nodes.cpp.

Usage:
    python generate_cycles_sockets.py <cyclesphi_root> [output.py]
"""

import os
import re
import sys

SOCKET_RE = re.compile(r'\bSOCKET_(IN_|OUT_)?([A-Z0-9_]+?)\s*\(\s*([A-Za-z0-9_.]+)\s*,\s*"([^"]*)"')
NODE_DEFINE_RE = re.compile(r'^NODE_DEFINE\((\w+)\)\s*$', re.M)
NODE_ADD_RE = re.compile(r'NodeType::add\(\s*"(\w+)"')
MACRO_RE = re.compile(r'^#define\s+(\w+_DEFINE)\((\w+)\)\s*\\\n((?:.*\\\n)*.*\n)', re.M)

# Macros that are not sockets.
SKIP_MACROS = {"OFFSETOF", "SIZEOF", "DEFINE"}


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def parse_sockets(body, macros):
    for name, macro_body in macros.items():
        body = re.sub(r'\b' + name + r'\(\w+\)\s*;', macro_body, body)

    inputs = []
    outputs = []
    for m in SOCKET_RE.finditer(body):
        kind, stype, name, ui_name = m.groups()
        if stype in SKIP_MACROS:
            continue
        stype = stype.lower()
        if kind == "OUT_":
            outputs.append((name, ui_name, stype))
        else:
            # SOCKET_IN_* are linkable (ShaderInput), the others are node parameters only.
            inputs.append((name, ui_name, stype, kind == "IN_"))
    return inputs, outputs


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1

    root = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "addons", "braas_hpc_xmlmaterial",
        "braas_hpc_xmlmaterial_sockets.py")

    nodes = {}
    # shader_nodes.cpp: all shader graph nodes, shader.cpp: the Shader itself (material settings).
    for src_name, only_class in (("shader_nodes.cpp", None), ("shader.cpp", "Shader")):
        src_path = os.path.join(root, "src", "scene", src_name)
        with open(src_path, encoding="utf-8") as f:
            text = strip_comments(f.read())

        macros = {}
        for m in MACRO_RE.finditer(text):
            macros[m.group(1)] = m.group(3).replace("\\\n", "\n")

        for m in NODE_DEFINE_RE.finditer(text):
            if only_class and m.group(1) != only_class:
                continue
            end = text.find("return type;", m.end())
            body = text[m.end():end]
            add = NODE_ADD_RE.search(body)
            if not add:
                continue
            inputs, outputs = parse_sockets(body, macros)
            nodes[add.group(1)] = (m.group(1), inputs, outputs)

    lines = [
        "# Generated by tools/generate_cycles_sockets.py from CyclesPhi src/scene/shader_nodes.cpp",
        "# and src/scene/shader.cpp.",
        "# Do not edit by hand, re-run the generator when the Cycles shader nodes change.",
        "#",
        "# CYCLES_NODES[xml_type] = (class_name,",
        "#     inputs:  [(name, ui_name, type, linkable), ...],",
        "#     outputs: [(name, ui_name, type), ...])",
        "",
        "CYCLES_NODES = {",
    ]
    for xml_type in sorted(nodes):
        class_name, inputs, outputs = nodes[xml_type]
        lines.append(f"    {xml_type!r}: ({class_name!r}, [")
        for s in inputs:
            lines.append(f"        {s!r},")
        lines.append("    ], [")
        for s in outputs:
            lines.append(f"        {s!r},")
        lines.append("    ]),")
    lines.append("}")
    lines.append("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"{len(nodes)} node types written to {os.path.abspath(out_path)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
